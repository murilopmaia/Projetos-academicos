def iterative_IDA(problem, f, limit):
    """[Figure 3.17]"""

    def recursive_dls(node, problem, f, limit):
        
        if problem.goal_test(node.state):
            return node
        elif f(node) > limit:
            return f(node)
        else:
            cutoff_occurred = False
            resultOld = np.inf
            for child in node.expand(problem):
                result = recursive_dls(child, problem, f, limit)
                if isinstance(result, float) or isinstance(result, int):
                    result = min(result, resultOld)
                    resultOld = result
                    cutoff_occurred = True
                elif result is not None:
                    return result
            return result if cutoff_occurred else None

    # Body of depth_limited_search:
    return recursive_dls(Node(problem.initial), problem, f, limit)


