def astar_search(problem, h=None, display=False):
    """A* search is best-first graph search with f(n) = g(n)+h(n).
    You need to specify the h function when you call astar_search, or
    else in your Problem subclass."""
    h = memoize(h or problem.h, 'h')  #é uma técnica de programação que armazena em memória o resultado de uma função para um determinado conjunto de argumentos, de modo a evitar recalcular esse resultado sempre que a função é chamada com os mesmos argumentos. Isso é feito para melhorar o desempenho, evitando cálculos redundantes
    # problem.h -> função que calcula a distancia reta entre os estados
    return best_first_graph_search(problem, lambda n: n.path_cost + h(n), display)


